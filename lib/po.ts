// Output stage: purchase order drafts. Nothing is ever sent automatically.
// PurchaseOrderClient is the seam for Zoho. DryRunZohoClient (default) records the exact payload a Zoho Inventory PO needs
// (in Postgres, and as out/po_drafts/<po>.json when running locally). ZohoInventoryClient has the real API shape but is
// disabled unless ZOHO_PO_ENABLED=true, and is never used by tests.
import fs from "node:fs";
import path from "node:path";
import type { Db } from "./db";
import { KillSwitchEngaged, requireOff } from "./killswitch";
import { auditStmt, now } from "./store";
import { j } from "./store";

export interface PurchaseOrderClient {
  readonly name: string;
  createPurchaseOrder(poNumber: string, payload: ZohoPo): Promise<{ file?: string }>;
}

export type ZohoPo = {
  purchaseorder_number: string; date: string; reference_number: string; vendor_id: string | null; vendor_name_hint: string; status: "draft";
  line_items: { item_id: string | null; sku: string; name: string; quantity: number; rate: number | null; unit: string }[]; notes: string;
};

export class DryRunZohoClient implements PurchaseOrderClient {
  readonly name = "dry_run_zoho";
  constructor(private outDir: string | null = process.env.VERCEL ? null : path.join(process.cwd(), "out", "po_drafts")) {}
  async createPurchaseOrder(poNumber: string, payload: ZohoPo) {
    if (!this.outDir) return {};                       // serverless filesystem is read-only: the payload lives in Postgres
    fs.mkdirSync(this.outDir, { recursive: true });
    const file = path.join(this.outDir, `${poNumber}.json`);
    fs.writeFileSync(file, JSON.stringify(payload, null, 2));
    return { file };
  }
}

/** POST {base}/purchaseorders?organization_id={org}. Disabled by default. */
export class ZohoInventoryClient implements PurchaseOrderClient {
  readonly name = "zoho_inventory";
  async createPurchaseOrder(_poNumber: string, payload: ZohoPo): Promise<{ file?: string }> {
    if ((process.env.ZOHO_PO_ENABLED ?? "false").toLowerCase() !== "true") throw new Error("ZohoInventoryClient is disabled. Set ZOHO_PO_ENABLED=true to switch it on.");
    const { ZOHO_ORG_ID: org, ZOHO_ACCESS_TOKEN: token, ZOHO_API_BASE: base = "https://www.zohoapis.in/inventory/v1" } = process.env;
    if (!org || !token) throw new Error("ZOHO_ORG_ID and ZOHO_ACCESS_TOKEN are required");
    const r = await fetch(`${base}/purchaseorders?organization_id=${org}`, {
      method: "POST", headers: { Authorization: `Zoho-oauthtoken ${token}`, "Content-Type": "application/json" }, body: JSON.stringify(payload),
    });
    if (!r.ok) throw new Error(`Zoho responded ${r.status}`);
    return {};
  }
}

export const getPoClient = (): PurchaseOrderClient =>
  (process.env.ZOHO_PO_ENABLED ?? "false").toLowerCase() === "true" ? new ZohoInventoryClient() : new DryRunZohoClient();

type RecRow = { rec_id: number; run_id: number; sku_id: string; sku_name: string; distributor_id: string; action: string; priority: string; status: string; recommended_qty: number; final_qty: number | null };

export function buildPayload(rec: RecRow, qty: number, poNumber: string): ZohoPo {
  return {
    purchaseorder_number: poNumber, date: new Date().toISOString().slice(0, 10),
    reference_number: `freshroots-run-${rec.run_id}-rec-${rec.rec_id}`,
    vendor_id: null,                       // needs mapping from Zoho master data
    vendor_name_hint: rec.distributor_id, status: "draft",
    line_items: [{ item_id: null, sku: rec.sku_id, name: rec.sku_name, quantity: qty, rate: null, unit: "Units" }],
    notes: `Draft generated by Freshroots after approval of recommendation ${rec.rec_id} (${rec.action}, priority ${rec.priority}).`,
  };
}

/** APPROVED reorder -> PO_DRAFTED. Blocked by the kill switch; never called without an approval. Returns the PO number or null. */
export async function createPoDraft(db: Db, recId: number, client: PurchaseOrderClient, actor: string): Promise<string | null> {
  await requireOff(db, "purchase order creation");
  const rec = (await db.query<RecRow>("SELECT * FROM recommendations WHERE rec_id=$1", [recId]))[0];
  if (!rec) throw new Error(`Unknown recommendation ${recId}`);
  if (rec.status !== "APPROVED") throw new Error(`Recommendation ${recId} is ${rec.status}, not APPROVED`);
  const qty = rec.final_qty ?? rec.recommended_qty;
  if (!["REORDER_NOW", "REORDER_HIGH_DEMAND"].includes(rec.action) || !qty || qty <= 0) return null;   // pauses need no PO
  const poNumber = `FR-PO-${rec.run_id}-${rec.sku_id}-${recId}`;
  const payload = buildPayload(rec, qty, poNumber);
  const res = await client.createPurchaseOrder(poNumber, payload);
  await db.batch([
    { text: "INSERT INTO po_drafts(po_number,rec_id,run_id,sku_id,ts,actor,quantity,client,payload,status) VALUES($1,$2,$3,$4,$5,$6,$7,$8,$9::jsonb,'DRAFT')", params: [poNumber, recId, rec.run_id, rec.sku_id, now(), actor, qty, client.name, j(payload)] },
    { text: "UPDATE recommendations SET status='PO_DRAFTED', updated_at=$2 WHERE rec_id=$1", params: [recId, now()] },
    auditStmt(actor, "PO_DRAFTED", "recommendation", recId, rec.run_id, { po_number: poNumber, quantity: qty, client: client.name, file: res.file ?? null }),
  ]);
  return poNumber;
}
