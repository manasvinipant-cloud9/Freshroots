"""Output stage: purchase order drafts. Nothing is ever sent automatically.

PurchaseOrderClient is the seam for Zoho. DryRunZohoClient (default) writes the exact
payload a Zoho Inventory PO needs to out/po_drafts/. ZohoInventoryClient has the real
API shape but is disabled unless ZOHO_PO_ENABLED=true and is never used by tests.
"""
from __future__ import annotations

import json
import os
from abc import ABC, abstractmethod
from datetime import date
from pathlib import Path
from typing import Any, Dict, Optional

from freshroots.killswitch import require_off
from freshroots.store import Store, now


class PurchaseOrderClient(ABC):
    name = "abstract"

    @abstractmethod
    def create_purchase_order(self, po_number: str, payload: Dict[str, Any]) -> Dict[str, Any]:
        """Create a draft PO. Returns {'file_path': ..} or the remote response."""


class DryRunZohoClient(PurchaseOrderClient):
    name = "dry_run_zoho"

    def __init__(self, out_dir: Path):
        self.out_dir = Path(out_dir)

    def create_purchase_order(self, po_number, payload):
        self.out_dir.mkdir(parents=True, exist_ok=True)
        path = self.out_dir / ("%s.json" % po_number)
        path.write_text(json.dumps(payload, indent=2, default=str))
        return {"file_path": str(path)}


class ZohoInventoryClient(PurchaseOrderClient):
    """POST {base}/purchaseorders?organization_id={org}. Disabled by default."""
    name = "zoho_inventory"

    def __init__(self):
        self.enabled = os.environ.get("ZOHO_PO_ENABLED", "false").lower() == "true"
        self.base = os.environ.get("ZOHO_API_BASE", "https://www.zohoapis.in/inventory/v1")
        self.org_id = os.environ.get("ZOHO_ORG_ID", "")
        self.token = os.environ.get("ZOHO_ACCESS_TOKEN", "")

    def create_purchase_order(self, po_number, payload):
        if not self.enabled:
            raise RuntimeError("ZohoInventoryClient is disabled. Set ZOHO_PO_ENABLED=true to switch it on.")
        if not (self.org_id and self.token):
            raise RuntimeError("ZOHO_ORG_ID and ZOHO_ACCESS_TOKEN are required")
        import urllib.request
        req = urllib.request.Request(
            "%s/purchaseorders?organization_id=%s" % (self.base, self.org_id),
            data=json.dumps(payload).encode(),
            headers={"Authorization": "Zoho-oauthtoken %s" % self.token, "Content-Type": "application/json"},
            method="POST")
        with urllib.request.urlopen(req, timeout=30) as r:  # pragma: no cover - never run in tests
            return json.loads(r.read().decode())


def get_client(po_drafts_dir: Path) -> PurchaseOrderClient:
    if os.environ.get("ZOHO_PO_ENABLED", "false").lower() == "true":
        return ZohoInventoryClient()
    return DryRunZohoClient(po_drafts_dir)


def build_payload(rec: Dict[str, Any], qty: float, po_number: str) -> Dict[str, Any]:
    """Zoho Inventory purchase order shape. vendor_id / item_id need mapping from Zoho master data."""
    return {
        "purchaseorder_number": po_number,
        "date": date.today().isoformat(),
        "reference_number": "freshroots-run-%s-rec-%s" % (rec["run_id"], rec["rec_id"]),
        "vendor_id": None,
        "vendor_name_hint": rec["distributor_id"],
        "status": "draft",
        "line_items": [{
            "item_id": None,
            "sku": rec["sku_id"],
            "name": rec["sku_name"],
            "quantity": qty,
            "rate": None,
            "unit": "Units",
        }],
        "notes": "Draft generated by Freshroots after approval of recommendation %s (%s, priority %s)."
                 % (rec["rec_id"], rec["action"], rec["priority"]),
    }


def create_po_draft(store: Store, rec_id: int, client: PurchaseOrderClient, user: str) -> Optional[str]:
    """APPROVED reorder -> PO_DRAFTED. Blocked by the kill switch; never called without an approval."""
    require_off(store, "purchase order creation")
    rec = store.one("SELECT * FROM recommendations WHERE rec_id=?", (rec_id,))
    if rec is None:
        raise ValueError("Unknown recommendation %s" % rec_id)
    if rec["status"] != "APPROVED":
        raise ValueError("Recommendation %s is %s, not APPROVED" % (rec_id, rec["status"]))
    qty = rec["final_qty"] if rec["final_qty"] is not None else rec["recommended_qty"]
    if rec["action"] not in ("REORDER_NOW", "REORDER_HIGH_DEMAND") or not qty or qty <= 0:
        return None   # pause actions and zero quantities need no PO
    po_number = "FR-PO-%s-%s-%s" % (rec["run_id"], rec["sku_id"], rec_id)
    payload = build_payload(rec, qty, po_number)
    res = client.create_purchase_order(po_number, payload)
    with store.conn() as c:
        c.execute("INSERT INTO po_drafts(po_number,rec_id,run_id,sku_id,ts,user,quantity,client,file_path,payload,status)"
                  " VALUES(?,?,?,?,?,?,?,?,?,?,?)",
                  (po_number, rec_id, rec["run_id"], rec["sku_id"], now(), user, qty, client.name,
                   res.get("file_path"), json.dumps(payload), "DRAFT"))
        c.execute("UPDATE recommendations SET status='PO_DRAFTED', updated_at=? WHERE rec_id=?", (now(), rec_id))
        store.audit(user, "PO_DRAFTED", "recommendation", rec_id, rec["run_id"],
                    {"po_number": po_number, "quantity": qty, "client": client.name}, conn=c)
    return po_number
